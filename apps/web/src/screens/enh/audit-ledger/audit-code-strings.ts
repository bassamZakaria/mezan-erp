function prefixed<T extends Record<string, string>, P extends string>(prefix: P, labels: T): { [K in keyof T & string as `${P}${K}`]: T[K] } {
  return Object.fromEntries(Object.entries(labels).map(([code, label]) => [`${prefix}${code}`, label])) as { [K in keyof T & string as `${P}${K}`]: T[K] };
}

