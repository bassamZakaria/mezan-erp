/**
 * قائمة المواد (Bill of Materials) — the versioned recipe for a finished product
 * (docs/archive/catalog/07 §BOMs): raw-material lines with waste %, plus standard labour
 * and overhead cost, produced in a standard batch quantity. A work order is
 * built from a BOM. Versioning REPLACES rather than mutates: creating a new
 * version supersedes the prior active version (نشط → غير نشط) and bumps the
 * version number, so historical work orders keep referencing the exact recipe
 * they were planned against.
 */

import { Money, Qty } from "../money/index.js";
import { extend, unitCostOf } from "../inventory/index.js";
import { NextNumberService } from "../numbering/index.js";
import type { ActivationStatus } from "./types.js";
import {
  BomNotFoundError,
  InvalidManufacturingDocumentError,
} from "./errors.js";

const BOM_SEQUENCE = "BOM";

export interface BomLine {
  readonly itemId: string;
  readonly qty: Qty;
  /** Expected material loss %, grossing up the required quantity (docs/archive/catalog/07). */
  readonly wastePercent: number;
  /** اختياري — an optional material (docs/archive/catalog/07). */
  readonly optional: boolean;
  readonly notes: string | null;
}

export interface Bom {
  readonly id: string;
  readonly number: string;
  readonly productItemId: string;
  readonly version: number;
  readonly standardQty: Qty;
  readonly unit: string;
  readonly laborCost: Money;
  readonly overheadCost: Money;
  readonly versionNotes: string | null;
  readonly lines: readonly BomLine[];
  readonly status: ActivationStatus;
  /** True for the ad-hoc BOM auto-generated by a custom-manufacturing order. */
  readonly custom: boolean;
  readonly createdBy: string;
  readonly createdAt: string;
}

export interface BomRepository {
  findById(id: string): Promise<Bom | null>;
  list(): Promise<Bom[]>;
  listByProduct(productItemId: string): Promise<Bom[]>;
  create(bom: Bom): Promise<void>;
  update(bom: Bom): Promise<void>;
}

export interface BomLineInput {
  readonly itemId: string;
  readonly qty: Qty;
  readonly wastePercent?: number;
  readonly optional?: boolean;
  readonly notes?: string | null;
}

export interface CreateBomCommand {
  readonly id: string;
  readonly productItemId: string;
  readonly standardQty: Qty;
  readonly unit: string;
  readonly laborCost?: Money;
  readonly overheadCost?: Money;
  readonly versionNotes?: string | null;
  readonly lines: readonly BomLineInput[];
  readonly createdBy?: string;
  readonly custom?: boolean;
}

export interface BomDeps {
  readonly boms: BomRepository;
  readonly numbering: NextNumberService;
  readonly now?: () => string;
}

function nowIso(deps: { now?: () => string }): string {
  return deps.now ? deps.now() : new Date().toISOString();
}

// --- pure computations ------------------------------------------------------

/**
 * Gross up a net required quantity for expected material loss: qty × (1 +
 * waste%/100), rounded HALF_UP to scale 1e-6. Waste is applied on the magnitude
 * so a zero-waste line returns exactly its input.
 */
export function grossUpForWaste(qty: Qty, wastePercent: number): Qty {
  if (wastePercent === 0) return qty;
  const wasteMicro = BigInt(Math.round(wastePercent * 1_000_000)); // waste% × 1e6
  const denom = 100_000_000n; // 100 × 1e6
  const num = qty.scaled * wasteMicro;
  const q = num / denom;
  const rem = num % denom;
  const extra = rem * 2n >= denom ? q + 1n : q;
  return Qty.fromScaled(qty.scaled + extra);
}

/**
 * The waste ALLOWANCE already baked into a grossed-up quantity — the inverse
 * reading of {@link grossUpForWaste}.
 *
 * `requiredQty` is net × (1 + p/100), so the allowance inside it is
 * requiredQty × p / (100 + p), rounded HALF_UP at scale 1e-6. This is the line
 * between normal and abnormal loss: scrap up to the allowance is what the BOM
 * planned for and belongs in the product's cost; scrap beyond it is a loss of
 * the period (EAS/IAS 2).
 */
export function wasteAllowanceOf(requiredQty: Qty, wastePercent: number): Qty {
  if (wastePercent <= 0) return Qty.zero();
  const wasteMicro = BigInt(Math.round(wastePercent * 1_000_000)); // waste% × 1e6
  const denom = 100_000_000n + wasteMicro; // (100 + waste%) × 1e6
  const num = requiredQty.scaled * wasteMicro;
  const q = num / denom;
  const rem = num % denom;
  return Qty.fromScaled(rem * 2n >= denom ? q + 1n : q);
}

/** Effective (post-waste) required quantity for one BOM line. */
export function bomLineEffectiveQty(line: Pick<BomLine, "qty" | "wastePercent">): Qty {
  return grossUpForWaste(line.qty, line.wastePercent);
}

/** Standard material cost of a BOM: Σ (effective qty × item unit cost). */
export function bomMaterialCost(bom: Bom, resolveUnitCost: (itemId: string) => Money): Money {
  return Money.sum(bom.lines.map((l) => extend(bomLineEffectiveQty(l), resolveUnitCost(l.itemId))));
}

export interface BomCostEstimate {
  readonly materialCost: Money;
  readonly laborCost: Money;
  readonly overheadCost: Money;
  readonly totalCost: Money;
  /** totalCost ÷ standardQty (weighted-average per-unit cost). */
  readonly unitCost: Money;
}

/** Full standard cost estimate for a BOM (docs/archive/catalog/07 §التكلفة التقديرية). */
export function bomCostEstimate(bom: Bom, resolveUnitCost: (itemId: string) => Money): BomCostEstimate {
  const materialCost = bomMaterialCost(bom, resolveUnitCost);
  const totalCost = materialCost.add(bom.laborCost).add(bom.overheadCost);
  return {
    materialCost,
    laborCost: bom.laborCost,
    overheadCost: bom.overheadCost,
    totalCost,
    unitCost: unitCostOf(totalCost, bom.standardQty),
  };
}

// --- use-cases --------------------------------------------------------------

function validateLines(command: CreateBomCommand): BomLine[] {
  const reasons: string[] = [];
  if (command.productItemId.trim() === "") reasons.push("المنتج النهائي مطلوب");
  if (command.standardQty.isZero() || command.standardQty.isNegative()) {
    reasons.push("كمية الدفعة القياسية يجب أن تكون أكبر من صفر");
  }
  if (command.lines.length === 0) reasons.push("مطلوب سطر واحد على الأقل من المواد الخام");
  const lines = command.lines.map<BomLine>((l, i) => {
    if (l.itemId.trim() === "") reasons.push(`السطر ${i}: الصنف مطلوب`);
    if (l.qty.isZero() || l.qty.isNegative()) reasons.push(`السطر ${i}: الكمية يجب أن تكون أكبر من صفر`);
    const waste = l.wastePercent ?? 0;
    if (waste < 0) reasons.push(`السطر ${i}: نسبة الهدر يجب ألا تكون سالبة`);
    return {
      itemId: l.itemId,
      qty: l.qty,
      wastePercent: waste,
      optional: l.optional ?? false,
      notes: l.notes ?? null,
    };
  });
  if (reasons.length > 0) throw new InvalidManufacturingDocumentError(reasons);
  return lines;
}

async function insertBom(command: CreateBomCommand, deps: BomDeps): Promise<Bom> {
  const lines = validateLines(command);

  // Supersede any active version for this product, and compute the next version.
  const existing = await deps.boms.listByProduct(command.productItemId);
  const maxVersion = existing.reduce((m, b) => Math.max(m, b.version), 0);
  for (const prior of existing) {
    if (prior.status === "active") {
      await deps.boms.update({ ...prior, status: "inactive" });
    }
  }

  const number = await deps.numbering.next(BOM_SEQUENCE);
  const bom: Bom = {
    id: command.id,
    number: number.formatted,
    productItemId: command.productItemId,
    version: maxVersion + 1,
    standardQty: command.standardQty,
    unit: command.unit,
    laborCost: command.laborCost ?? Money.zero(),
    overheadCost: command.overheadCost ?? Money.zero(),
    versionNotes: command.versionNotes ?? null,
    lines,
    status: "active",
    custom: command.custom ?? false,
    createdBy: command.createdBy ?? "system",
    createdAt: nowIso(deps),
  };
  await deps.boms.create(bom);
  return bom;
}

/** Create a new BOM (version 1 for a new product, or the next version, superseding the active one). */
export async function createBom(command: CreateBomCommand, deps: BomDeps): Promise<Bom> {
  return insertBom(command, deps);
}

export interface CreateBomVersionCommand {
  readonly id: string;
  readonly sourceBomId: string;
  readonly standardQty?: Qty;
  readonly unit?: string;
  readonly laborCost?: Money;
  readonly overheadCost?: Money;
  readonly versionNotes?: string | null;
  readonly lines?: readonly BomLineInput[];
  readonly createdBy?: string;
}

/**
 * إصدار جديد (New version) — clone a BOM's product/recipe into a superseding
 * next version. Fields present on the command override the source; omitted ones
 * (including `lines`) are copied from the source BOM.
 */
export async function createBomVersion(
  command: CreateBomVersionCommand,
  deps: BomDeps,
): Promise<Bom> {
  const source = await deps.boms.findById(command.sourceBomId);
  if (!source) throw new BomNotFoundError(command.sourceBomId);
  return insertBom(
    {
      id: command.id,
      productItemId: source.productItemId,
      standardQty: command.standardQty ?? source.standardQty,
      unit: command.unit ?? source.unit,
      laborCost: command.laborCost ?? source.laborCost,
      overheadCost: command.overheadCost ?? source.overheadCost,
      versionNotes: command.versionNotes ?? null,
      lines:
        command.lines ??
        source.lines.map((l) => ({
          itemId: l.itemId,
          qty: l.qty,
          wastePercent: l.wastePercent,
          optional: l.optional,
          notes: l.notes,
        })),
      createdBy: command.createdBy,
      custom: source.custom,
    },
    deps,
  );
}

/** تعطيل (Deactivate) — نشط → غير نشط. Idempotent. */
export async function deactivateBom(
  id: string,
  deps: Pick<BomDeps, "boms">,
): Promise<Bom> {
  const bom = await deps.boms.findById(id);
  if (!bom) throw new BomNotFoundError(id);
  if (bom.status === "inactive") return bom;
  const updated: Bom = { ...bom, status: "inactive" };
  await deps.boms.update(updated);
  return updated;
}
