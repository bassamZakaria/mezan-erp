import { describe, expect, it } from "vitest";
import { assertSchemaName, InvalidSchemaNameError } from "./postgres-db.js";
import { translateDdl, UntranslatableDdlError } from "./translate-ddl.js";

describe("assertSchemaName", () => {
  it("accepts a t_-prefixed lowercase identifier", () => {
    expect(assertSchemaName("t_acme_01")).toBe("t_acme_01");
  });

  it.each(["public", "pg_catalog", "information_schema", "tenant_acme", "t_", "T_acme", "t_a-1", "t_a;drop schema x", "t_a\n", "", `t_${"x".repeat(62)}`])("refuses %j", (name) => {
    expect(() => assertSchemaName(name)).toThrow(InvalidSchemaNameError);
  });
});

describe("translateDdl", () => {
  it("widens every integer to 64 bits and maps SQLite-only types", () => {
    expect(translateDdl("CREATE TABLE IF NOT EXISTS t (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER NOT NULL, r REAL, b BLOB) WITHOUT ROWID;")).toBe(
      "CREATE TABLE IF NOT EXISTS t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT NOT NULL, r DOUBLE PRECISION, b BYTEA);",
    );
  });

  it("refuses a trigger, which needs a Postgres-specific script", () => {
    expect(() => translateDdl("CREATE TRIGGER x BEFORE UPDATE ON t BEGIN SELECT 1; END;")).toThrow(UntranslatableDdlError);
  });
});
