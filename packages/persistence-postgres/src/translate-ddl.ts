const RULES: ReadonlyArray<readonly [RegExp, string]> = [
  [/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"],
  [/\bINTEGER\s+PRIMARY\s+KEY\b/gi, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"],
  [/\bINTEGER\b/gi, "BIGINT"],
  [/\bINT\b/gi, "BIGINT"],
  [/\bREAL\b/gi, "DOUBLE PRECISION"],
  [/\bBLOB\b/gi, "BYTEA"],
  [/\)\s*WITHOUT\s+ROWID\s*;/gi, ");"],
  [/\)\s*STRICT\s*;/gi, ");"],
];

export class UntranslatableDdlError extends Error {
  constructor(readonly construct: string) {
    super(`This DDL uses ${construct}, which has no automatic Postgres form; give the store a Postgres-specific script for it.`);
  }
}

// INVARIANT: a Postgres INTEGER is 32-bit. Every SQLite INTEGER becomes BIGINT,
// or a scaled money column overflows at about 2,147 in major units.
export function translateDdl(ddl: string): string {
  if (/\bCREATE\s+TRIGGER\b/i.test(ddl)) throw new UntranslatableDdlError("CREATE TRIGGER");
  if (/\bCREATE\s+VIRTUAL\s+TABLE\b/i.test(ddl)) throw new UntranslatableDdlError("CREATE VIRTUAL TABLE");
  return RULES.reduce((sql, [pattern, replacement]) => sql.replace(pattern, replacement), ddl);
}
